use std::path::Path;

use super::*;

#[test]
fn well_known_lockfiles_resolve_by_filename() {
    for name in [
        "Cargo.lock",
        "package-lock.json",
        "yarn.lock",
        "pnpm-lock.yaml",
        "go.sum",
        "Gemfile.lock",
        "flake.lock",
        "uv.lock",
    ] {
        assert_eq!(
            generated_for_path(Path::new(name)),
            Some(Generated::Lockfile),
            "{name}"
        );
    }
}

#[test]
fn a_lockfile_is_recognized_wherever_it_sits() {
    assert_eq!(
        generated_for_path(Path::new("crates/karet-core/Cargo.lock")),
        Some(Generated::Lockfile)
    );
}

#[test]
fn filenames_match_case_insensitively() {
    assert_eq!(
        generated_for_path(Path::new("cargo.lock")),
        Some(Generated::Lockfile)
    );
    assert_eq!(
        generated_for_path(Path::new("GEMFILE.LOCK")),
        Some(Generated::Lockfile)
    );
}

#[test]
fn directory_rules_match_any_segment_not_just_the_root() {
    // The whole point of a directory rule: a vendored tree is vendored wherever
    // it is nested.
    assert_eq!(
        generated_for_path(Path::new("vendor/foo.rs")),
        Some(Generated::Vendored)
    );
    assert_eq!(
        generated_for_path(Path::new("crates/app/vendor/deep/foo.rs")),
        Some(Generated::Vendored)
    );
    assert_eq!(
        generated_for_path(Path::new("web/node_modules/left-pad/index.js")),
        Some(Generated::Vendored)
    );
    assert_eq!(
        generated_for_path(Path::new("app/target/debug/build.rs")),
        Some(Generated::BuildOutput)
    );
}

#[test]
fn suffix_rules_cover_minified_and_codegen_output() {
    let cases = [
        ("app.min.js", Generated::Minified),
        ("theme.min.css", Generated::Minified),
        ("main.bundle.js", Generated::Minified),
        ("app.js.map", Generated::Minified),
        ("api.pb.go", Generated::BuildOutput),
        ("service_pb2.py", Generated::BuildOutput),
        ("model.g.dart", Generated::BuildOutput),
        ("Form.designer.cs", Generated::BuildOutput),
        ("render.snap", Generated::Snapshot),
    ];
    for (name, expected) in cases {
        assert_eq!(
            generated_for_path(Path::new(name)),
            Some(expected),
            "{name}"
        );
    }
}

#[test]
fn a_longer_suffix_convention_wins_over_a_shorter_one() {
    // `.min.js` and `.js.map` must not be reported as anything but Minified, and
    // `.pb.go` must not fall through to a plain Go file.
    assert_eq!(
        generated_for_path(Path::new("bundle.min.js")),
        Some(Generated::Minified)
    );
    assert_eq!(
        generated_for_path(Path::new("grpc.pb.go")),
        Some(Generated::BuildOutput)
    );
}

#[test]
fn ordinary_source_files_are_not_generated() {
    for name in [
        "src/main.rs",
        "README.md",
        "app.js",
        "styles.css",
        "Cargo.toml",
        "api.go",
        "service.py",
    ] {
        assert_eq!(generated_for_path(Path::new(name)), None, "{name}");
    }
}

#[test]
fn a_name_that_merely_contains_a_rule_word_is_not_generated() {
    // Substring matching would be a disaster here: these are hand-written files
    // whose names happen to embed a rule token.
    for name in [
        "src/lockfile_utils.rs",
        "src/vendor_client.rs",
        "src/build_script.rs",
        "docs/target-audience.md",
        "src/distance.rs",
    ] {
        assert_eq!(generated_for_path(Path::new(name)), None, "{name}");
    }
}

#[test]
fn a_suffix_rule_needs_something_in_front_of_it() {
    // A file literally named `.lock` is a dotfile, not `<something>.lock`.
    assert_eq!(generated_for_path(Path::new(".lock")), None);
    assert_eq!(generated_for_path(Path::new(".snap")), None);
}

#[test]
fn a_directory_rule_does_not_fire_on_a_partial_segment() {
    assert_eq!(generated_for_path(Path::new("vendors/foo.rs")), None);
    assert_eq!(generated_for_path(Path::new("distribution/foo.rs")), None);
    assert_eq!(generated_for_path(Path::new("rebuild/foo.rs")), None);
}

#[test]
fn every_variant_has_a_distinct_terse_reason() {
    let all = [
        Generated::Lockfile,
        Generated::Minified,
        Generated::Vendored,
        Generated::BuildOutput,
        Generated::Snapshot,
        Generated::Marker,
    ];
    let mut seen = Vec::new();
    for kind in all {
        let reason = kind.reason();
        assert!(!reason.is_empty(), "{kind:?}");
        assert_eq!(
            reason,
            reason.to_lowercase(),
            "{kind:?} must stay lowercase"
        );
        assert!(!seen.contains(&reason), "{kind:?} duplicates {reason:?}");
        seen.push(reason);
    }
}

#[test]
fn a_banner_marks_an_otherwise_ordinary_path() {
    let head = "// Code generated by protoc-gen-go. DO NOT EDIT.\n\npackage api\n";
    assert_eq!(
        generated_for_content(Path::new("src/api.go"), head),
        Some(Generated::Marker)
    );
}

#[test]
fn the_at_generated_convention_is_recognized() {
    assert_eq!(
        generated_for_content(
            Path::new("src/schema.ts"),
            "/* @generated */\n\nexport {};\n"
        ),
        Some(Generated::Marker)
    );
}

#[test]
fn banners_match_case_insensitively() {
    assert_eq!(
        generated_for_content(Path::new("a.rs"), "// AUTO-GENERATED\n\nfn main() {}\n"),
        Some(Generated::Marker)
    );
}

#[test]
fn a_path_rule_outranks_the_banner_sniff() {
    // The specific reason is more useful to a reader than the generic one.
    assert_eq!(
        generated_for_content(Path::new("Cargo.lock"), "# @generated\n"),
        Some(Generated::Lockfile)
    );
}

#[test]
fn content_without_a_banner_stays_hand_written() {
    assert_eq!(
        generated_for_content(Path::new("src/main.rs"), "fn main() {}\n"),
        None
    );
}

#[test]
fn a_banner_below_the_header_block_does_not_count() {
    // Prose deep in a file saying "do not edit" is not a generated banner.
    let head = "# Title\n\nSome prose.\n\nPlease do not edit this section.\n";
    assert_eq!(generated_for_content(Path::new("README.md"), head), None);
}

#[test]
fn a_banner_past_the_guard_does_not_count() {
    let mut head = String::new();
    head.push_str("// header\n");
    head.push_str(&"// filler line\n".repeat(200));
    head.push_str("// @generated\n");
    assert!(head.len() > BANNER_GUARD);
    assert_eq!(generated_for_content(Path::new("a.rs"), &head), None);
}

#[test]
fn a_multibyte_header_does_not_defeat_the_guard() {
    // The guard walks down to a char boundary; a header of multibyte characters
    // must not fall back to scanning the whole string.
    let mut head = "// ".to_string();
    head.push_str(&"é".repeat(BANNER_GUARD));
    head.push_str("@generated");
    assert_eq!(generated_for_content(Path::new("a.rs"), &head), None);
}

#[test]
fn an_empty_head_is_not_generated() {
    assert_eq!(generated_for_content(Path::new("a.rs"), ""), None);
}
